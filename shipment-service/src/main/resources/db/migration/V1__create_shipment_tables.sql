CREATE TABLE shipments (
                           id                       UUID PRIMARY KEY,
                           version                  BIGINT,

                           customer_id              UUID NOT NULL,
                           status                   VARCHAR(255) NOT NULL,
                           service_type             VARCHAR(255) NOT NULL,
                           weight                   NUMERIC NOT NULL,

                           origin_address_line      VARCHAR(255) NOT NULL,
                           origin_city              VARCHAR(255) NOT NULL,
                           origin_country_code      VARCHAR(255) NOT NULL,

                           destination_address_line VARCHAR(255) NOT NULL,
                           destination_city         VARCHAR(255) NOT NULL,
                           destination_country_code VARCHAR(255) NOT NULL,

                           sender_name              VARCHAR(255) NOT NULL,
                           sender_phone             VARCHAR(255) NOT NULL,
                           recipient_name           VARCHAR(255) NOT NULL,
                           recipient_phone          VARCHAR(255) NOT NULL,

                           created_at               TIMESTAMP(6) WITH TIME ZONE NOT NULL,
                           updated_at               TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE shipment_items (
                                id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                shipment_id UUID NOT NULL,
                                line_number INTEGER NOT NULL,
                                description VARCHAR(255) NOT NULL,
                                quantity    INTEGER NOT NULL,

                                CONSTRAINT fk_shipment_items_shipment
                                    FOREIGN KEY (shipment_id)
                                        REFERENCES shipments (id),

                                CONSTRAINT uk_shipment_item_line
                                    UNIQUE (shipment_id, line_number)
);

CREATE INDEX idx_shipments_created_at_id
    ON shipments (created_at DESC, id DESC);